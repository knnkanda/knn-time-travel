export function getRandomSampleNovel(exclude?: SampleNovel): SampleNovel {
  const candidates = exclude
    ? sampleNovels.filter((novel) => novel !== exclude)
    : sampleNovels;
  const pool = candidates.length > 0 ? candidates : sampleNovels;
  const index = Math.floor(Math.random() * pool.length);
  return pool[index];
}
